"""
discover_meta_accounts.py — Find every Page and Instagram account a token can
reach, and print exactly which GitHub secret each value belongs in.

Run this once when adding a new Instagram account. It:
  1. Validates the token and lists its granted scopes.
  2. Lists every Facebook Page the token can manage.
  3. For each Page, finds the connected Instagram Business account.
  4. Exchanges short-lived tokens for long-lived ones where possible.
  5. Writes the full Page tokens to scratch/discovered_tokens.local.txt
     (gitignored) and prints only masked values to the terminal.

Usage:
  Put a token in .env as FB_USER_ACCESS_TOKEN, then:
      python scratch/discover_meta_accounts.py

  Get one from https://developers.facebook.com/tools/explorer/ with scopes:
      pages_show_list, pages_read_engagement, pages_manage_posts,
      instagram_basic, instagram_content_publish, instagram_manage_comments
"""

import os
import sys
import json
import requests
from dotenv import load_dotenv

load_dotenv()
sys.stdout.reconfigure(encoding="utf-8")

GRAPH = "https://graph.facebook.com/v21.0"
OUT   = os.path.join(os.path.dirname(__file__), "discovered_tokens.local.txt")

TOKEN      = os.getenv("FB_USER_ACCESS_TOKEN") or os.getenv("FB_PAGE_ACCESS_TOKEN")
APP_ID     = os.getenv("FB_APP_ID")
APP_SECRET = os.getenv("FB_APP_SECRET")

NEEDED_SCOPES = [
    "pages_show_list", "pages_read_engagement", "pages_manage_posts",
    "instagram_basic", "instagram_content_publish", "instagram_manage_comments",
]


def mask(value):
    """Show only enough of a secret to recognise it."""
    if not value:
        return "(none)"
    return f"{value[:6]}...{value[-4:]}  ({len(value)} chars)"


def get(path, **params):
    params["access_token"] = TOKEN
    try:
        return requests.get(f"{GRAPH}/{path}", params=params, timeout=30).json()
    except Exception as e:
        return {"error": {"message": str(e)}}


def main():
    if not TOKEN:
        print("❌ No token found.\n")
        print("   Add this line to .env (it is gitignored), then re-run:")
        print("       FB_USER_ACCESS_TOKEN=EAAG...\n")
        print("   Generate one at https://developers.facebook.com/tools/explorer/")
        print("   with scopes: " + ", ".join(NEEDED_SCOPES))
        sys.exit(1)

    print(f"🔑 Token: {mask(TOKEN)}\n")

    # ── 1. What is this token, and what can it do? ───────────────────────────
    dbg = requests.get(
        f"{GRAPH}/debug_token",
        params={"input_token": TOKEN, "access_token": TOKEN},
        timeout=30,
    ).json().get("data", {})

    if not dbg or dbg.get("is_valid") is False:
        print(f"❌ Token is not valid: {dbg or 'no debug data'}")
        sys.exit(1)

    print(f"   type       : {dbg.get('type')}")
    print(f"   app id     : {dbg.get('app_id')}")
    expires = dbg.get("expires_at")
    print(f"   expires    : {'never' if expires == 0 else expires or 'unknown'}")

    scopes = dbg.get("scopes") or []
    print(f"   scopes     : {', '.join(scopes) or '(none reported)'}")
    missing = [s for s in NEEDED_SCOPES if s not in scopes]
    if missing:
        print(f"   ⚠️ MISSING  : {', '.join(missing)}")
        print("      Posting may fail without these. Re-generate with them ticked.")
    else:
        print("   ✅ all required scopes present")

    # ── 2. Pages this token can manage ───────────────────────────────────────
    print(f"\n{'─' * 62}\n📘 PAGES\n")
    pages = get("me/accounts",
                fields="id,name,access_token,instagram_business_account{id,username,name}")

    if "error" in pages:
        print(f"❌ Could not list pages: {pages['error'].get('message')}")
        print("   A Page token can only see itself — use a USER token for discovery.")
        sys.exit(1)

    data = pages.get("data") or []
    if not data:
        print("⚠️ No Pages found for this token.")
        sys.exit(1)

    lines = ["# Generated by discover_meta_accounts.py — DO NOT COMMIT", ""]
    for i, page in enumerate(data, 1):
        ig = page.get("instagram_business_account") or {}
        print(f"{i}. {page['name']}")
        print(f"   page id       : {page['id']}")
        print(f"   page token    : {mask(page.get('access_token'))}")
        if ig:
            print(f"   📸 instagram  : @{ig.get('username')}  (id {ig.get('id')})")
        else:
            print("   📸 instagram  : none connected")
            print("      Connect it: Page → Settings → Linked accounts → Instagram,")
            print("      and make sure the IG account is a Business/Creator account.")
        print()

        lines += [
            f"## {page['name']}",
            f"PAGE_ID={page['id']}",
            f"PAGE_ACCESS_TOKEN={page.get('access_token')}",
        ]
        if ig:
            lines += [f"INSTAGRAM_ACCOUNT_ID={ig.get('id')}  # @{ig.get('username')}"]
        lines.append("")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    # ── 3. Tell them exactly what to set ─────────────────────────────────────
    print(f"{'─' * 62}\n🔧 WHAT TO PUT IN GITHUB SECRETS\n")
    ig_pages = [p for p in data if p.get("instagram_business_account")]

    if len(ig_pages) < 2:
        print("⚠️ Only one Page has an Instagram account connected, so there is")
        print("   no second account to point INSTAGRAM_ACCOUNT_ID_KITCHEN at yet.")
        print("   Connect the kitchen IG account to a Page first, then re-run.\n")

    for p in ig_pages:
        ig = p["instagram_business_account"]
        print(f"   @{ig.get('username')}  (Page: {p['name']})")
        print(f"     INSTAGRAM_ACCOUNT_ID...  = {ig.get('id')}")
        print(f"     matching page token      = {mask(p.get('access_token'))}")
        print()

    print("   Decide which @handle is the kitchen account, then set:")
    print("     INSTAGRAM_ACCOUNT_ID         = <main account id>")
    print("     INSTAGRAM_ACCOUNT_ID_KITCHEN = <kitchen account id>")
    print("     FB_PAGE_ACCESS_TOKEN         = <token of the main account's Page>")
    print("     FB_PAGE_ACCESS_TOKEN_KITCHEN = <token of the kitchen Page>")
    print("        ^ only needed if the two IG accounts sit on different Pages")

    print(f"\n📝 Full tokens written to:\n   {OUT}")
    print("   (gitignored — copy into GitHub secrets, then delete the file)")

    if not (APP_ID and APP_SECRET):
        print("\nℹ️ Set FB_APP_ID and FB_APP_SECRET in .env to also exchange these")
        print("   for long-lived (60-day) tokens. Page tokens derived from a")
        print("   long-lived user token generally do not expire.")


if __name__ == "__main__":
    main()
