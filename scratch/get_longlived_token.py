"""
get_longlived_token.py — Turn a short-lived token into Page tokens that don't expire.

Graph API Explorer hands out tokens that die in 1-2 hours, which is useless as
a GitHub secret. The fix is a two-step exchange:

    short-lived USER token
      -> long-lived USER token   (60 days, needs the app secret)
      -> PAGE tokens             (derived from a long-lived user token,
                                  these generally never expire)

Usage:
  Put these in .env, then run `python scratch/get_longlived_token.py`:

      FB_APP_ID=1245867192740342
      FB_APP_SECRET=<from your app's Settings -> Basic>
      FB_USER_ACCESS_TOKEN=<short-lived USER token from Graph API Explorer>

  The USER token matters: a Page token cannot enumerate Pages, so discovery
  and this exchange both need a user token. Scopes required:
      pages_show_list, pages_read_engagement, pages_manage_posts,
      instagram_basic, instagram_content_publish, instagram_manage_comments
"""

import os
import sys
import json
import datetime
import requests
from dotenv import load_dotenv

load_dotenv()
sys.stdout.reconfigure(encoding="utf-8")

GRAPH = "https://graph.facebook.com/v21.0"
OUT   = os.path.join(os.path.dirname(__file__), "longlived_tokens.local.txt")

APP_ID     = os.getenv("FB_APP_ID")
APP_SECRET = os.getenv("FB_APP_SECRET")
SHORT      = os.getenv("FB_USER_ACCESS_TOKEN")


def mask(v):
    return f"{v[:6]}...{v[-4:]} ({len(v)} chars)" if v else "(none)"


def describe(token):
    """Return (type, expires_at) for a token, or (None, None)."""
    d = requests.get(f"{GRAPH}/debug_token",
                     params={"input_token": token, "access_token": token},
                     timeout=30).json().get("data", {})
    return d.get("type"), d.get("expires_at")


def fmt_expiry(exp):
    if exp in (0, None):
        return "never ✅"
    when = datetime.datetime.fromtimestamp(exp, datetime.timezone.utc)
    left = when - datetime.datetime.now(datetime.timezone.utc)
    if left.total_seconds() <= 0:
        return f"{when:%Y-%m-%d %H:%M} UTC — ALREADY EXPIRED ❌"
    return f"{when:%Y-%m-%d %H:%M} UTC ({left.days}d {left.seconds // 3600}h left)"


def main():
    missing = [n for n, v in
               [("FB_APP_ID", APP_ID), ("FB_APP_SECRET", APP_SECRET),
                ("FB_USER_ACCESS_TOKEN", SHORT)] if not v]
    if missing:
        print(f"❌ Missing in .env: {', '.join(missing)}\n")
        print(__doc__)
        sys.exit(1)

    kind, exp = describe(SHORT)
    print(f"🔑 Input token: {mask(SHORT)}")
    print(f"   type    : {kind}")
    print(f"   expires : {fmt_expiry(exp)}\n")

    if kind == "PAGE":
        print("❌ This is a PAGE token. The exchange needs a USER token.")
        print("   In Graph API Explorer the dropdown above the token field")
        print("   must say 'User Token', not the name of a Page.")
        sys.exit(1)

    # ── Step 1: long-lived user token ───────────────────────────────────────
    print("1️⃣  Exchanging for a long-lived user token...")
    res = requests.get(f"{GRAPH}/oauth/access_token", params={
        "grant_type": "fb_exchange_token",
        "client_id": APP_ID,
        "client_secret": APP_SECRET,
        "fb_exchange_token": SHORT,
    }, timeout=30).json()

    long_user = res.get("access_token")
    if not long_user:
        print(f"❌ Exchange failed: {res.get('error', {}).get('message', res)}")
        sys.exit(1)

    _, lexp = describe(long_user)
    print(f"   ✅ got it — expires {fmt_expiry(lexp)}\n")

    # ── Step 2: page tokens ─────────────────────────────────────────────────
    print("2️⃣  Fetching Page tokens (these inherit the long life)...")
    pages = requests.get(f"{GRAPH}/me/accounts", params={
        "fields": "id,name,access_token,instagram_business_account{id,username}",
        "access_token": long_user,
    }, timeout=30).json()

    if "error" in pages:
        print(f"❌ {pages['error'].get('message')}")
        sys.exit(1)

    data = pages.get("data") or []
    if not data:
        print("⚠️ No Pages returned — check the pages_show_list scope.")
        sys.exit(1)

    lines = ["# Generated by get_longlived_token.py — DO NOT COMMIT", ""]
    print()
    for p in data:
        ig = p.get("instagram_business_account") or {}
        _, pexp = describe(p["access_token"])
        print(f"   📘 {p['name']}  (page {p['id']})")
        print(f"      token   : {mask(p['access_token'])}")
        print(f"      expires : {fmt_expiry(pexp)}")
        if ig:
            print(f"      📸 @{ig.get('username')}  (ig id {ig.get('id')})")
        print()

        lines += [f"## {p['name']}",
                  f"PAGE_ID={p['id']}",
                  f"PAGE_ACCESS_TOKEN={p['access_token']}"]
        if ig:
            lines += [f"INSTAGRAM_ACCOUNT_ID={ig.get('id')}  # @{ig.get('username')}"]
        lines.append("")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"📝 Full tokens written to:\n   {OUT}")
    print("   (gitignored — copy into GitHub secrets, then delete this file)")


if __name__ == "__main__":
    main()
